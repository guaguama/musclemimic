#!/usr/bin/env python3
"""Vendor the MyoAssist full-body + OSL export into models/osl_fullbody/.

The source is a local artifact of the myoassist checkout, produced by the
``assist_sim`` CLI with myo_sim 0.2.3 and then hand edited::

    cd <myoassist repo>
    python -m assist_sim combine myofullbody OpenSourceLeg_KA_L1 \
        -o models/osl_fullbody_v3.xml

The hand edit lengthens the OSL tibial pylon by 22.5 mm so the prosthetic leg
matches the intact leg.  The comment block at the top of the source records the
exact edit; it is kept verbatim in the vendored files.

``assist_sim.utils.export_combined_xml`` rewrites mesh paths relative to the
*output* file and strips ``meshdir``, so re-exporting straight into this repo
does not make the model portable -- it would just point back at this machine's
``myo_sim`` checkout and ``.venv``.  This script is what makes it standalone.

Four edits, all mechanical, applied to the export's own serialization rather
than through ``MjSpec`` (``MjSpec.to_xml()`` reorders elements and re-serializes
every float to six significant figures, which would bury the real diff and
perturb inertias):

1. Mesh paths.  The 108 ``file=`` attributes are reduced to bare basenames and
   ``meshdir="../meshes"`` is added to the existing ``<compiler>``; the 76
   unique STLs are copied into ``meshes/``.  ``texturedir`` is deliberately not
   set: the scene's skybox is referenced bare and MuJoCo resolves it against the
   *including* file's directory.
2. The export's builtin ``<texture name="sky" builtin="gradient">`` is deleted.
   It is not cosmetic -- the scene declares a file-backed texture of the same
   name, and duplicate texture names are a hard compile error.
3. The exporter's ``<visual>`` boilerplate (``_ensure_minimal_visual``) is
   deleted so the scene's headlight/haze/camera values win outright.
4. ``<include file="../scene/musclemimic_scene.xml"/>`` supplies the floor,
   light, and skybox the export does not ship.  The scene files are tracked in
   ``models/osl_fullbody/scene/`` and are not regenerated; this script only
   checks that they are present.

Two model files are emitted.
--------------------------

``osl_fullbody.xml`` is the official rigid-socket topology (nq 120).
``osl_fullbody_compliant_socket.xml`` additionally restores the four compliant
socket DoFs of the hand-assembled model (now on the ``old_osl`` branch), spelled
out in ``SOCKET_JOINTS``.  The transplant is exact, not approximate: in both
models the socket body is a direct child of ``femur_r`` with no ``quat`` and an
identical ``<inertial>``, and all four joints sit at ``pos="0 0 0"``, so the axis
vectors carry over verbatim.  ``armature="0.01"`` is stated explicitly because
the official model's socket body inherits no ``myolegs`` default class.

Why two files instead of one file plus a runtime toggle: the export ships five
keyframes, and deleting a joint from a spec that has keyframes fails to compile
(``keyframe 'stand': invalid qpos size``).  Adding is safe, deleting is not, so
the compliant variant is *generated* and the environment selects a path.

The two variants are a coupled toggle with ``mjDSBL_EULERDAMP``.  At the 2 ms
timestep training uses, the rigid model's worst ``dof_damping * dt / M_ii`` is
0.995 (a finger joint) -- inside the explicit-Euler bound of 2, so Euler damping
may be disabled.  With the socket restored, ``socket_rotation_3`` reaches 15.68
and the model raises ``mjWARN_BADQACC`` on the first step from key ``stand``
unless Euler damping stays implicit.  The failure belongs to the socket, not to
the prosthesis.
"""

from __future__ import annotations

import argparse
import filecmp
import re
import shutil
import sys
from pathlib import Path

import mujoco


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE_XML = Path(
    "/home/dmma/src/00_AMBER/01_projpegleg/myoassist/models/osl_fullbody_v3.xml"
)
OUTPUT_ROOT = REPO_ROOT / "models" / "osl_fullbody"
SCENE_FILES = ("musclemimic_scene.xml", "musclemimic_skybox.png")

MODEL_NAME = "OSLFullBody"
RIGID_XML = OUTPUT_ROOT / "body" / "osl_fullbody.xml"
COMPLIANT_XML = OUTPUT_ROOT / "body" / "osl_fullbody_compliant_socket.xml"

BANNER = (
    "  <!-- Generated by scripts/vendor_osl_fullbody_model.py; "
    "do not edit manually. -->"
)

SOCKET_BODY = "OSL_KA_L1_osl_generic_socket"
# The joint immediately following the socket body in tree order.  Its addresses
# in the rigid model are where the socket DoFs land in the compliant one.
JOINT_AFTER_SOCKET = "OSL_KA_L1_osl_knee_angle_r"

# Transplanted verbatim from the hand-assembled model's leg/assets/myolegs_chain.xml
# (old_osl branch).
# armature is stated explicitly; the official socket body inherits no class.
SOCKET_JOINTS = (
    '<joint name="socket_piston" type="slide" pos="0 0 0"'
    ' axis="-0.124293 0.989762 0.0701648" range="-0.035 0.035"'
    ' stiffness="20000" damping="10000" armature="0.01" />',
    '<joint name="socket_rotation_1" pos="0 0 0" axis="0 0 1"'
    ' range="-0.122173 0.122173" stiffness="350" damping="175" armature="0.01" />',
    '<joint name="socket_rotation_2" pos="0 0 0" axis="1 0 0"'
    ' range="-0.122173 0.122173" stiffness="350" damping="175" armature="0.01" />',
    '<joint name="socket_rotation_3" pos="0 0 0" axis="0 1 0"'
    ' range="-0.122173 0.122173" stiffness="350" damping="175" armature="0.01" />',
)
SOCKET_JOINT_NAMES = ("socket_piston", "socket_rotation_1", "socket_rotation_2", "socket_rotation_3")

# (nq, nv, nu, nbody, neq, na, nkey); na is the 401 muscle activation states
RIGID_DIMENSIONS = (120, 119, 403, 106, 44, 401, 5)
COMPLIANT_DIMENSIONS = (124, 123, 403, 106, 44, 401, 5)
EXPECTED_MASS = 82.28906  # 82.27817 stock export + 10.9 g from the lengthened pylon


def _mesh_sources(source_xml: Path) -> dict[str, Path]:
    """Map basename -> absolute STL path, resolved against the export's dir."""
    text = source_xml.read_text(encoding="utf-8")
    sources: dict[str, Path] = {}
    for reference in re.findall(r'file="([^"]+)"', text):
        path = (source_xml.parent / reference).resolve()
        name = path.name
        previous = sources.get(name)
        if previous is not None and previous != path:
            raise RuntimeError(f"mesh basename collision: {name} -> {previous}, {path}")
        if not path.is_file():
            raise RuntimeError(f"missing source asset: {reference} -> {path}")
        sources[name] = path
    return sources


def _rewrite(source_xml: Path) -> str:
    """Apply the four documented edits to the export's own serialization."""
    xml = source_xml.read_text(encoding="utf-8")

    # 1. mesh paths -> bare basenames, resolved through meshdir
    xml = re.sub(r'file="([^"]+)"', lambda m: f'file="{Path(m.group(1)).name}"', xml)
    compiler = '<compiler angle="radian" />'
    if xml.count(compiler) != 1:
        raise RuntimeError(f"expected exactly one {compiler!r} in the export")
    xml = xml.replace(compiler, '<compiler angle="radian" meshdir="../meshes" />', 1)

    # 2. builtin skybox -- collides with the scene's file-backed texture
    sky = re.search(r'\n *<texture type="skybox"[^>]*name="sky"[^>]*/>', xml)
    if sky is None:
        raise RuntimeError("builtin skybox texture not found in the export")
    xml = xml[: sky.start()] + xml[sky.end() :]

    # 3. exporter <visual> boilerplate -- let the scene's values win
    visual = re.search(r"\n *<visual>.*?</visual>", xml, flags=re.DOTALL)
    if visual is None:
        raise RuntimeError("exporter <visual> block not found in the export")
    xml = xml[: visual.start()] + xml[visual.end() :]

    # 4. our floor / light / skybox, plus the model name and the banner
    root = f'<mujoco model="{MODEL_NAME}">'
    # The source opens with a provenance comment, so anchor on a line start rather
    # than the string start; a bare `^` would silently match nothing.
    xml, renamed = re.subn(r'^<mujoco model="[^"]*">', root, xml, count=1, flags=re.MULTILINE)
    if renamed != 1:
        raise RuntimeError("root <mujoco> element not found in the export")
    xml = xml.replace(
        root,
        f'{root}\n{BANNER}\n  <include file="../scene/musclemimic_scene.xml" />',
        1,
    )
    return xml


def _socket_addresses(rigid_xml: str) -> tuple[int, int]:
    """qpos/qvel offsets the four socket DoFs occupy in the compliant model."""
    model = _compile(rigid_xml, RIGID_XML)
    joint = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, JOINT_AFTER_SOCKET)
    if joint < 0:
        raise RuntimeError(f"{JOINT_AFTER_SOCKET} not found in the rigid model")
    return int(model.jnt_qposadr[joint]), int(model.jnt_dofadr[joint])


def _splice(values: str, index: int, count: int) -> str:
    items = values.split()
    if index > len(items):
        raise RuntimeError(f"splice index {index} past keyframe of length {len(items)}")
    return " ".join(items[:index] + ["0"] * count + items[index:])


def _add_compliant_socket(rigid_xml: str) -> str:
    """Insert the socket DoFs and widen the keyframes to match."""
    qpos_adr, qvel_adr = _socket_addresses(rigid_xml)

    body = re.search(rf'( *)<body name="{SOCKET_BODY}"[^>]*>\n', rigid_xml)
    if body is None:
        raise RuntimeError(f"socket body {SOCKET_BODY} not found")
    indent = body.group(1) + "  "
    block = f"{indent}<!-- compliant socket (musclemimic addition; see the module docstring) -->\n"
    block += "".join(f"{indent}{joint}\n" for joint in SOCKET_JOINTS)
    xml = rigid_xml[: body.end()] + block + rigid_xml[body.end() :]

    def widen(match: re.Match[str]) -> str:
        attribute, values = match.group(1), match.group(2)
        index = qpos_adr if attribute == "qpos" else qvel_adr
        return f'{attribute}="{_splice(values, index, len(SOCKET_JOINTS))}"'

    keyframe = re.search(r"<keyframe>.*</keyframe>", xml, flags=re.DOTALL)
    if keyframe is None:
        raise RuntimeError("no <keyframe> block to widen")
    widened = re.sub(r'\b(qpos|qvel)="([^"]*)"', widen, keyframe.group(0))
    return xml[: keyframe.start()] + widened + xml[keyframe.end() :]


def _compile(xml: str, destination: Path) -> mujoco.MjModel:
    """Compile through a sibling temp file so asset resolution matches usage."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix(".xml.tmp")
    temporary.write_text(xml, encoding="utf-8")
    try:
        return mujoco.MjModel.from_xml_path(str(temporary))
    finally:
        temporary.unlink(missing_ok=True)


def _dimensions(model: mujoco.MjModel) -> tuple[int, ...]:
    return (model.nq, model.nv, model.nu, model.nbody, model.neq, model.na, model.nkey)


def _verify(model: mujoco.MjModel, expected: tuple[int, ...], label: str) -> None:
    actual = _dimensions(model)
    if actual != expected:
        raise RuntimeError(f"{label}: unexpected dimensions {actual}, expected {expected}")
    mass = float(model.body_mass.sum())
    if abs(mass - EXPECTED_MASS) > 1e-4:
        raise RuntimeError(f"{label}: mass {mass:.5f} != {EXPECTED_MASS}")


def _verify_compliant(model: mujoco.MjModel, qpos_adr: int) -> None:
    for offset, name in enumerate(SOCKET_JOINT_NAMES):
        joint = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, name)
        if joint < 0:
            raise RuntimeError(f"compliant model is missing {name}")
        if int(model.jnt_qposadr[joint]) != qpos_adr + offset:
            raise RuntimeError(
                f"{name} at qposadr {int(model.jnt_qposadr[joint])}, expected {qpos_adr + offset}"
            )
    knee = mujoco.mj_name2id(model, mujoco.mjtObj.mjOBJ_JOINT, JOINT_AFTER_SOCKET)
    if int(model.jnt_qposadr[knee]) != qpos_adr + len(SOCKET_JOINT_NAMES):
        raise RuntimeError("knee joint did not shift by the four socket DoFs")


def _copy_assets(sources: dict[str, Path], check: bool) -> list[str]:
    """Copy meshes; in check mode report what differs instead.

    The scene is tracked in place and never copied (see the module docstring).
    """
    stale: list[str] = []
    meshes = OUTPUT_ROOT / "meshes"
    wanted = {meshes / name: path for name, path in sources.items()}
    if check:
        for destination, origin in wanted.items():
            if not destination.is_file() or not filecmp.cmp(destination, origin, shallow=False):
                stale.append(str(destination.relative_to(REPO_ROOT)))
        extra = {p for p in meshes.glob("*") if p.is_file()} - set(wanted)
        stale.extend(sorted(str(p.relative_to(REPO_ROOT)) for p in extra))
        return stale

    meshes.mkdir(parents=True, exist_ok=True)
    for destination, origin in wanted.items():
        shutil.copyfile(origin, destination)
    for path in meshes.glob("*"):
        if path.is_file() and path not in wanted:
            path.unlink()
    return stale


def build(source_xml: Path) -> tuple[str, str]:
    """Serialize both variants.  Assets must already be on disk: deriving the
    socket's keyframe offsets means compiling the rigid model first."""
    rigid = _rewrite(source_xml)
    compliant = _add_compliant_socket(rigid)
    return rigid, compliant


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        type=Path,
        default=DEFAULT_SOURCE_XML,
        help="the `assist_sim combine` export to vendor",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the tracked model tree differs from deterministic regeneration",
    )
    args = parser.parse_args()

    if not args.source.is_file():
        print(f"source export not found: {args.source}", file=sys.stderr)
        return 2

    # Assets first: both variants compile through meshdir="../meshes", and the
    # compliant one derives its keyframe offsets from a compile of the rigid one.
    sources = _mesh_sources(args.source)
    stale_assets = _copy_assets(sources, check=args.check)
    if not all((OUTPUT_ROOT / "scene" / n).is_file() for n in SCENE_FILES):
        print("models/osl_fullbody/scene is missing; it is tracked, not generated", file=sys.stderr)
        return 1

    rigid, compliant = build(args.source)

    rigid_model = _compile(rigid, RIGID_XML)
    _verify(rigid_model, RIGID_DIMENSIONS, "rigid")
    qpos_adr, _ = _socket_addresses(rigid)

    compliant_model = _compile(compliant, COMPLIANT_XML)
    _verify(compliant_model, COMPLIANT_DIMENSIONS, "compliant")
    _verify_compliant(compliant_model, qpos_adr)

    if args.check:
        stale = list(stale_assets)
        for path, xml in ((RIGID_XML, rigid), (COMPLIANT_XML, compliant)):
            if not path.exists() or path.read_text(encoding="utf-8") != xml:
                stale.append(str(path.relative_to(REPO_ROOT)))
        if stale:
            print("out of date:\n  " + "\n  ".join(stale), file=sys.stderr)
            return 1
        print("models/osl_fullbody is up to date")
        return 0

    RIGID_XML.write_text(rigid, encoding="utf-8")
    COMPLIANT_XML.write_text(compliant, encoding="utf-8")
    print(
        f"wrote {RIGID_XML.relative_to(REPO_ROOT)} (nq {rigid_model.nq}) and "
        f"{COMPLIANT_XML.relative_to(REPO_ROOT)} (nq {compliant_model.nq}); "
        f"{len(sources)} meshes"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

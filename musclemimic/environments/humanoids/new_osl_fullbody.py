"""NewOSLFullBody -- the official MyoAssist full-body + OSL knee-ankle prosthesis.

This is the upstream replacement for :class:`OSLFullBody`, which grafted the
``myoLeg80_OSL_KA`` prosthetic leg onto the packaged MyoFullBody model by hand.
The model tree lives at ``models/new_osl_fullbody/`` and is regenerated by
``scripts/vendor_new_osl_fullbody_model.py``; ``OSLFullBody`` is untouched.

Why this subclasses :class:`MyoFullBody` and not :class:`OSLFullBody`
--------------------------------------------------------------------
Every OSL-specific override in ``osl_fullbody.py`` is now wrong or unnecessary:

* its ``_get_observation_specification`` appends a ``r_osl_foot`` touch sensor that
  does not exist here -- the official model ships exactly ``r_foot``/``r_toes``/
  ``l_foot``/``l_toes``, i.e. the parent's hardcoded list is correct again;
* ``MjxOSLFullBody`` omits ``mjDSBL_EULERDAMP`` unconditionally, which is the wrong
  default once the socket is welded (see below);
* only 3 of the 17 ``body2sites_for_mimic`` entries actually differ.

The class *name* must keep ``OSLFullBody`` as a substring: ``create_site_mapper``
(``core/utils/site_mapping.py``) and ``runner/validation_video_recorder.py`` dispatch
on substrings of the class name, and ``"MyoFullBody"`` is tested first. A name that
matched neither would silently fall through to ``NoOpSiteMapper`` and index a
17-wide trajectory site array with model site ids in the thousands.

The socket / Euler-damping toggle
---------------------------------
``compliant_socket`` selects between the two generated MJCFs. It is a coupled toggle
with Euler damping, measured at the 2 ms timestep training uses (explicit-Euler bound
is 2.0):

===================================  ======  =========
worst ``dof_damping * dt / M_ii``    rigid   compliant
===================================  ======  =========
value                                0.995   15.68
offender                             finger  ``socket_rotation_3``
explicit Euler (EULERDAMP disabled)  stable  NaN by step 100 under Warp
===================================  ======  =========

So ``disable_eulerdamp`` defaults to ``not compliant_socket``: rigid matches plain
``MjxMyoFullBody``, compliant keeps damping implicit. The unsafe pairing raises
rather than diverging -- MuJoCo clamps ``qacc`` on instability, so it would surface
as a plausible-looking rollout and an ``mjWARN_BADQACC`` counter, not an obvious NaN.

Note the toggle changes ``nq``/``nv`` (120/119 vs 124/123, or 80/79 vs 84/83 with
fingers disabled), hence the observation size -- checkpoints are not portable across it.
"""


# The four extra DoFs the compliant-socket variant adds between the residual limb and the
# prosthesis.  Clipper generates its exports from the RIGID model, so a clip never names
# them; padding them to 0.0 is the neutral socket, which is exactly the rigid configuration
# (clipper measured FK as identical between the two variants under kinematic replay).  The
# gate below therefore exempts these four -- and only these four -- and only when the
# compliant variant is actually loaded.
_SOCKET_JOINTS = (
    "socket_piston",
    "socket_rotation_1",
    "socket_rotation_2",
    "socket_rotation_3",
)


class NewOSLFullBody(MyoFullBody):
    """Full-body muscle humanoid with the official OSL knee-ankle prosthesis."""

    mjx_enabled = False

    def __init__(
        self,
        compliant_socket: bool = False,
        disable_eulerdamp: bool | None = None,
        strict_trajectory_joints: bool = True,
        **kwargs,
    ) -> None:
        """
        Args:
            compliant_socket (bool): If True, load the variant with the four compliant
                socket DoFs (nq 124) instead of the official rigid weld (nq 120).
            disable_eulerdamp (bool | None): If None (default), tracks
                ``not compliant_socket``. Set explicitly only to override.
            strict_trajectory_joints (bool): If True (default), ``load_trajectory``
                refuses a trajectory that does not name every joint of this model.
        """
        self._compliant_socket = bool(compliant_socket)
        if disable_eulerdamp is None:
            disable_eulerdamp = not self._compliant_socket
        self._disable_eulerdamp = bool(disable_eulerdamp)
        if self._compliant_socket and self._disable_eulerdamp:
            raise ValueError(
                "compliant_socket=True with disable_eulerdamp=True is numerically unsafe: "
                "socket_rotation_3 reaches dof_damping*dt/M_ii = 15.68 at the 2 ms timestep "
                "against an explicit-Euler bound of 2.0, and diverges by step 100 under Warp. "
                "MuJoCo clamps qacc on instability, so this does not present as an obvious NaN."
            )
        self._strict_trajectory_joints = bool(strict_trajectory_joints)

        kwargs.setdefault("spec", self._variant_xml(self._compliant_socket))
        if "model_option_conf" not in kwargs:
            model_option_conf = dict(iterations=4, ls_iterations=8)
            if self._disable_eulerdamp:
                model_option_conf["disableflags"] = mujoco.mjtDisableBit.mjDSBL_EULERDAMP
            kwargs["model_option_conf"] = model_option_conf

        super().__init__(**kwargs)

    @classmethod
    def get_default_xml_file_path(cls) -> str:
        return _RIGID_XML.as_posix()

    @info_property
    def body2sites_for_mimic(self) -> dict[str, str]:
        """The parent's 17-site map with the three prosthetic bodies renamed.

        The site *names* are unchanged; every downstream index -- goal, reward,
        validation, site mapper -- resolves by name.
        """
        return {
            "pelvis": "pelvis_mimic",
            "lumbar1": "upper_body_mimic",
            "head": "head_mimic",
            # Left arm
            "humerus_l": "left_shoulder_mimic",
            "ulna_l": "left_elbow_mimic",
            "lunate_l": "left_hand_mimic",
            # Right arm
            "humerus_r": "right_shoulder_mimic",
            "ulna_r": "right_elbow_mimic",
            "lunate_r": "right_hand_mimic",
            # Biological left leg
            "femur_l": "left_hip_mimic",
            "tibia_l": "left_knee_mimic",
            "talus_l": "left_ankle_mimic",
            "toes_l": "left_toes_mimic",
            # Right leg: biological residual femur, then the prosthesis.  The OSL bodies
            # stand in for the amputated tibia_r/talus_r/toes_r.
            "femur_r": "right_hip_mimic",
            "OSL_KA_L1_osl_knee_assembly": "right_knee_mimic",
            "OSL_KA_L1_osl_ankle_assembly": "right_ankle_mimic",
            "OSL_KA_L1_osl_foot_assembly": "right_toes_mimic",
        }

    @classmethod
    def _variant_xml(cls, compliant_socket: bool) -> str:
        """The source XML for a socket variant.

        A hook rather than a module constant so a subclass can swap in a different
        pair of models while inheriting the ``compliant_socket`` toggle whole --
        which is exactly what ``NewOSLFullBodyRobot`` does.
        """
        return (_COMPLIANT_XML if compliant_socket else _RIGID_XML).as_posix()

    def _apply_spec_changes(self, spec: MjSpec) -> MjSpec:
        """Strip keyframes and delete fingers by their official names, then defer.

        Two things the parent cannot do on this model:

        1. The export ships five keyframes, and deleting a joint from a spec that has
           keyframes fails to compile (``keyframe 'stand': invalid qpos size``).
        2. The parent's finger name lists predate the official rename -- see
           ``_FINGER_JOINTS`` / ``_FINGER_MUSCLES``.

        The parent's finger block is suppressed with the same save/restore idiom
        ``OSLFullBody._get_observation_specification`` uses, so ``myofullbody.py``
        needs no change and the mimic-site and ctrlrange work still runs there.
        """
        for key in list(spec.keys):
            spec.delete(key)
        # `<size nkey="5"/>` allocates the slots independently of the `<keyframe>`
        # entries, so without this the model keeps five all-zero keys -- and an all-zero
        # qpos carries a zero root quaternion.
        spec.nkey = 0

        if self._disable_fingers:
            self._delete_fingers(spec)

        disable_fingers = self._disable_fingers
        self._disable_fingers = False
        try:
            return super()._apply_spec_changes(spec)
        finally:
            self._disable_fingers = disable_fingers

    @staticmethod
    def _delete_fingers(spec: MjSpec) -> None:
        """Mirror of the parent's finger removal with the official model's names."""
        for joint in [j for j in spec.joints if j.name in _FINGER_JOINTS]:
            spec.delete(joint)
        for actuator in [a for a in spec.actuators if a.name in _FINGER_MUSCLES]:
            spec.delete(actuator)
        # Tendons match by substring, as in the parent.  Verified against this model:
        # 62 tendons matched, all hand muscles, no false positives from OP/EDM/APL.
        for tendon in [t for t in spec.tendons if any(m in t.name for m in _FINGER_MUSCLES)]:
            spec.delete(tendon)

    def load_trajectory(
        self,
        traj=None,
        traj_path: str = None,
        warn: bool = True,
        cache_type="full",
        site_names=None,
    ) -> None:
        """Refuse a trajectory that does not name every joint of this model.

        ``TrajectoryHandler.filter_and_extend`` reconciles by name and silently pads a
        model joint the trajectory lacks with **0.0** -- no warning, no error.  The
        official export renames four joints relative to the ``osl_fullbody`` clips
        (both elbows and both prosthesis joints), so without this gate a run would
        train against a reference with straight arms and a frozen prosthesis and look
        entirely plausible.  Pass ``strict_trajectory_joints=False`` to opt out.
        """
        if self._strict_trajectory_joints:
            names = _peek_trajectory_joint_names(traj, traj_path)
            if names is not None:
                self._assert_trajectory_covers_model_joints(names)
        super().load_trajectory(
            traj=traj, traj_path=traj_path, warn=warn, cache_type=cache_type, site_names=site_names
        )
        self._normalize_trajectory_backend()

    def _normalize_trajectory_backend(self) -> None:
        """Force the freshly loaded trajectory back onto the numpy backend.

        ``filter_and_extend``'s padding path calls ``TrajectoryData.add_joint()``, whose
        ``backend`` argument defaults to ``jnp``, so a padded trajectory comes back with
        jax ``qpos``/``qvel`` but a numpy ``split_points``.  ``TrajectoryHandler`` decides
        ``is_numpy`` from ``qpos`` alone, so ``engine.instantiate_env``'s ``to_jax()`` then
        no-ops and ``split_points`` stays numpy -- which blows up inside ``mjx_reset`` with
        ``TracerArrayConversionError``.  Renormalizing here makes that conversion happen.

        Reachable two ways: with ``strict_trajectory_joints=False``, and -- since the gate
        exempts the four socket DoFs -- on **every** ``compliant_socket=True`` run, because a
        clipper clip never names them.  So this is load-bearing for the socket toggle, not
        just a guard for lenient mode.
        """
        if self.th is not None and not self.th.is_numpy:
            self.th.to_numpy()

    def _assert_trajectory_covers_model_joints(self, trajectory_joint_names) -> None:
        available = {str(name) for name in trajectory_joint_names}
        # Padding a socket DoF to 0.0 is the neutral socket, i.e. the rigid configuration, so
        # a rigid-model clip is a correct reference for the compliant variant too.  Exempt
        # them only when the compliant variant is loaded: on the rigid model these joints do
        # not exist, so a clip that omits them there is a genuine mismatch worth raising on.
        exempt = set(_SOCKET_JOINTS) if self._compliant_socket else set()
        missing = []
        padded = []
        for i in range(self._model.njnt):
            name = mujoco.mj_id2name(self._model, mujoco.mjtObj.mjOBJ_JOINT, i)
            if name is None or name in available:
                continue
            (padded if name in exempt else missing).append(name)
        if padded:
            print(
                f"[{type(self).__name__}] {len(padded)} socket DoF(s) absent from the "
                f"trajectory, padded to the neutral socket: {', '.join(padded)}."
            )
        if missing:
            raise RuntimeError(
                f"trajectory does not cover {len(missing)} joint(s) of "
                f"{type(self).__name__}: {', '.join(missing)}.\n"
                "These would be silently zero-padded by TrajectoryHandler.filter_and_extend. "
                "Regenerate the trajectory against models/new_osl_fullbody, or pass "
                "strict_trajectory_joints=False to accept the padding."
            )


def _peek_trajectory_joint_names(traj, traj_path):
    """Joint names of a trajectory before it is reconciled with the model, or None."""
    if traj is not None:
        info = getattr(traj, "info", None)
        return None if info is None else getattr(info, "joint_names", None)
    if traj_path is None:
        return None
    paths = [traj_path] if isinstance(traj_path, (str, Path)) else list(traj_path)
    names: set[str] = set()
    for path in paths:
        with np.load(path, allow_pickle=True) as handle:
            if "joint_names" not in handle:
                return None
            names.update(str(name) for name in handle["joint_names"])
    return sorted(names)


class MjxNewOSLFullBody(NewOSLFullBody, MjxMyoFullBody):
    """MJX variant. Euler damping follows the socket toggle resolved in __init__."""

    mjx_enabled = True

    def _modify_spec_for_mjx(self, spec: MjSpec) -> MjSpec:
        spec = super()._modify_spec_for_mjx(spec)
        if self.mjx_backend != "warp":
            # The parent zeroes contype/conaffinity on every non-floor geom outside the
            # Warp backend, which leaves MJX's touch sensors with no candidate contacts
            # to concatenate.  Same workaround as MjxOSLFullBodyRobot, with this model's
            # geom names.  Explicit pairs go too, for the same no-self-contact
            # approximation the parent already applies to geoms.
            for pair in list(spec.pairs):
                spec.delete(pair)
            for geom in spec.geoms:
                if geom.name in _TOUCH_CONTACT_GEOMS:
                    geom.contype = 1
        return spec
